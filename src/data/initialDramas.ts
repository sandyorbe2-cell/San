function generateEpisodes(dramaId: string, dramaTitle: string, count: number, posterUrl: string) {
  const titles = [
    'El Despertar de la Traición',
    'Firma del Divorcio Secreto',
    'La Revelación en la Fiesta de Gala',
    'Quién es el Verdadero Dueño',
    'La Arrogancia de la Rival',
    'El Chofer Que Mandó a los Guardaespaldas',
    'Venganza en la Junta Directiva',
    'El Beso Imprevisto en el Ascensor',
    'Prueba de ADN Irrefutable',
    'El Magnate Se Arrodilla por Amor',
    'Caída de la Familia Falsa',
    'La Verdad Sobre el Pasado',
    'Alianza Peligrosa en la Noche',
    'El Testamento Oculto',
    'La Coronación Final'
  ];

  return Array.from({ length: count }, (_, i) => {
    const epNum = i + 1;
    const titleSnippet = titles[(epNum - 1) % titles.length];
    return {
      id: `${dramaId}-ep-${epNum}`,
      dramaId,
      episodeNumber: epNum,
      title: `Capítulo ${epNum}: ${titleSnippet}`,
      duration: `${1 + ((epNum * 3) % 2)}:${String(15 + ((epNum * 7) % 45)).padStart(2, '0')}`,
      videoUrl: SAMPLE_VIDEOS[(epNum - 1) % SAMPLE_VIDEOS.length],
      videoType: 'sample' as const,
      thumbnail: posterUrl,
      synopsis: `En este capítulo de ${dramaTitle}, las tensiones aumentan cuando la verdad sale a la luz y los rivales descubren con quién se han metido.`,
      uploadedAt: new Date(Date.now() - (count - epNum) * 3600000 * 24).toISOString(),
      views: 12500 + epNum * 1420,
      likes: 1840 + epNum * 210,
    };
  });
}

